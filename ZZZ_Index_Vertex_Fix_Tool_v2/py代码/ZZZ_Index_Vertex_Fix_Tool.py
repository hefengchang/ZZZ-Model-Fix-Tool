class Style:
    RESET = '\033[0m'
    BOLD = '\033[1m'
    GREEN = '\033[1;32m'
    RED = '\033[1;31m'
    YELLOW = '\033[1;33m'
    CYAN = '\033[1;36m'
    GRAY = '\033[90m'


def c(text, color):
    return '{}{}{}'.format(color, text, Style.RESET)


def join_names(items):
    """列名字，按语言用顿号 / 逗号"""
    return ('、' if LANG == 'zh' else ', ').join(str(x) for x in items)


# ==========================================================================
#  命令行提问器（独立脚本默认用这套）
#
#  修复前要问用户几件事（表与 dump 撞车用哪套、写不写、还原确认）。
#  把 IV_ASKER 换成别的提问器（比如 GUI），同一处问话就能改成别的问法。
# ==========================================================================

IV_ASKER = None


class IvConsoleAsker:
    """命令行提问：独立脚本默认用这套"""

    def source_choice(self, kind, detail, count, prefer_dump):
        """表 / dump 撞车：返回 'table' 或 'dump'"""
        if kind == 'vgx':
            print(T('ask.source.vgx.1', '' if count == 1 else ' {} '.format(count), detail))
            print(T('ask.source.vgx.2'))
            print(T('ask.source.vgx.3', Style.GREEN, Style.RESET))
            print(T('ask.source.vgx.4', Style.GREEN, Style.RESET))
            return 'dump' if ask(T('ask.source.vgx.5')).strip() == '2' else 'table'
        print(T('ask.source.tex.1', '' if count == 1 else ' {} '.format(count), detail))
        print(T('ask.source.tex.2'))
        print(T('ask.source.tex.3', Style.GREEN, Style.RESET))
        print(T('ask.source.tex.4', Style.GREEN, Style.RESET))
        answer = ask(T('ask.source.tex.5', T('ask.dump') if prefer_dump else T('ask.table'))).strip()
        if answer == '1':
            return 'table'
        if answer == '2':
            return 'dump'
        return 'dump' if prefer_dump else 'table'

    def auto_vgx_choice(self, paths):
        """表里没有、dump 能推：返回 True = 用 dump 推的修"""
        print(T('ask.auto.head'))
        for path in paths:
            print('  - {}'.format(path))
        print(T('ask.auto.q'))
        print(T('ask.auto.1', Style.GREEN, Style.RESET))
        print(T('ask.auto.2', Style.GREEN, Style.RESET))
        return ask(T('ask.auto.ask')).strip() != '2'

    def confirm(self, summary):
        """写文件前的总确认：返回 True = 动手"""
        print(c(T('ask.danger1'), Style.RED))
        print(c(T('ask.danger2'), Style.RED))
        print(T('ask.confirm', Style.GREEN, CONFIRM_WORD, Style.RESET))
        return ask().lower() == CONFIRM_WORD

    def confirm_restore(self, lines):
        """还原确认：返回 True = 动手（明细行由调用方打印）"""
        print(T('ask.restore', Style.GREEN, CONFIRM_WORD, Style.RESET))
        return ask().lower() == CONFIRM_WORD

    def progress(self, done, total, text):
        """命令行不画进度条，什么都不做"""
        pass


def iv_asker():
    return IV_ASKER if IV_ASKER is not None else _IV_CONSOLE_ASKER


_IV_CONSOLE_ASKER = IvConsoleAsker()


def iv_progress(done, total, text):
    """写文件进度（换个提问器就能刷进度条；命令行忽略）"""
    if IV_ASKER is not None:
        try:
            IV_ASKER.progress(done, total, text)
        except Exception:
            pass


