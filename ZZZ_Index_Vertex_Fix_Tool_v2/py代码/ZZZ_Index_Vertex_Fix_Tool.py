# -*- coding: utf-8 -*-
r"""
    ZZZ Index & Vertex Fix Tool  v2   (中文 / English)
    绝区零 索引与顶点修复工具 v2

WHAT IT FIXES  /  修什么
    (1) Bone indices (VGX)    — model deforms: bent legs, collapse, twisting, textures fine.
        Symptoms come from wrong bone indices inside blend.buf.
        Fix: rewrite each weight slot's bone index using the correct mapping.

    (2) Vertex format (texcoord) — texture is scrambled all over, but the model shape is perfect.
        A game update changed the vertex layout; old mods' buf layout no longer matches.
        Fix: re-pack every vertex's bytes and sync the `stride` line in the ini.

    (3) Universal face fix (mode 2) — the 3.1 -> 3.2 face breakage.
        Only the leading vertex COLOR block changed: 4 bytes (R8G8B8A8_UNORM) -> 4 floats,
        i.e. 36 -> 48 bytes per vertex. One hard-coded list of mesh hashes, no reference needed.

WHERE THE DATA COMES FROM  /  数据从哪来
    The `Dump\` folder next to this script. A handful of common meshes ship with the
    package; the author does not keep it updated and covers no other mesh. Anything
    missing, capture yourself with gui_collect (XXMI "Enable Hunting" -> numpad 0
    in game -> export the mesh -> drop the folder into Dump\).
    Guide: https://leotorrez.github.io/modding/guides/hunting

    One sub-folder = one reference set. Each sub-folder holds a `hash.json` plus the
    text dumps of that mesh:

        Dump\
            Dialyn-Face\
                hash.json                      <- hashes of every buffer of this mesh
                DialynFaceA-vb0=c44d2531.txt   <- vertex data (text)
                DialynFaceA-ib=facb2461.txt    <- index data  (text)

    hash.json entries give texcoord_vb / blend_vb / position_vb / ib. Those hashes are
    matched against the hashes in the mod's ini, so the tool knows which buf to touch.
    The vertex text file gives the current element layout (what the texcoord format must
    become) and POSITION / BLENDWEIGHTS / BLENDINDICES (used to derive the bone map).

HOW TO USE  /  怎么用
    Double-click this script:
        1. pick the interface language (中文 / English)
        2. pick the mode      (1 = index & vertex fix, 2 = universal face fix, 3 = list)
        3. pick the reference set (a folder inside Dump\)
        4. drag ONE mod folder into the window, press Enter, then choose
           1 = fix / 2 = restore / Enter = skip / q = quit

    Command line:
        python ZZZ_Index_Vertex_Fix_Tool.py [-zh|-en] [universal] [restore] <mod folder>

    In the drag-drop window: `lang` switches language, `m` switches mode,
    `c` re-picks the reference set, `3` lists what the universal face fix covers, `q` quits.

NOTES  /  注意
    - ONE mod folder at a time (its own ini + Buffer). Never drag the whole Mods folder.
    - Never run twice on the same mod (already-done files are skipped automatically).
    - The mod must belong to the reference set you picked: if not one single reference hash
      is found in its ini, the whole folder is left untouched.
    - Everything is backed up before writing. Restore = option 2.

ADDING A NEW CHARACTER / MESH  /  加新角色
    VGX_CHARACTERS    — bone index remap table    (generated by the VGX mapping finder tool)
    TEXCOORD_TARGETS  — texcoord re-pack table    (generated by the texcoord mapping finder tool)
    Both tables are optional: anything present in Dump\ works without a table entry.

HOW IT WORKS  /  原理
    Bone indices: pair mod vertices with the game's by position (spatial grid, radius
    0.01), and where a skin weight agrees too, vote mod index -> game index; resolve
    the votes into a one-to-one mapping and rewrite blend.buf.
    Vertex format: re-pack each texcoord vertex to the layout read from the live dump
    (36 -> 48 bytes/vertex for the COLOR change) and sync the ini stride; only when
    buf size, vertex count and layout all agree, otherwise skip with a note.
    Full write-up, thresholds and limits: 原理说明.md / How It Works.

OPEN SOURCE  /  开源
    Completely open source. Modify it, build on it, publish your own version.
    It is meant to share an approach, not to be a finished product: it may be
    incomplete and it will not be updated further.
"""

