def ensure_reference():
    """索引与顶点修复模式下，确保这次已经选好一组参照

    每次进这个模式都要重新问一遍 —— 从通用模式换回来时，参照是上一轮留下的，
    不重选就会跨组匹配。通用模式不看参照，只把 dump 全都放着。
    """
    if FIX_MODE != 'normal':
        set_active_dumps(None)
        return
    if ALL_DUMPS:
        choose_character()
    else:
        set_active_dumps(None)


def ask_action(target: Path):
    """拖进来之后让用户选：修复 / 还原 / 换参照 / 跳过 / 退出

    换参照（c）在这里也留着 —— 拖进来才发现参照选错了，不用退出去重来。
    """
    print(T('act.target', target))
    while True:
        print(T('act.ask', c('1', Style.GREEN), c('2', Style.GREEN), c('q', Style.GRAY)))
        if FIX_MODE == 'normal':
            print(T('act.keyc', c('c', Style.GREEN)))
        try:
            choice = input(c(T('act.prompt'), Style.CYAN)).strip().lower()
        except (EOFError, KeyboardInterrupt):
            print()
            return 'quit'

        if choice == '':
            return None
        if choice in ('1', 'apply', 'fix', '修复'):
            return 'apply'
        if choice in ('2', 'restore', 'undo', '还原'):
            return 'restore'
        # 换参照组：换完留在原地接着问修不修
        if choice in ('c', 'juese', 'role', '角色', '换角色', '参照', '换参照'):
            if FIX_MODE == 'universal':
                print(c(T('ref.not.normal'), Style.YELLOW))
            elif ALL_DUMPS:
                choose_character()
                print(T('act.refchg', c(describe_active_dumps(), Style.GREEN)))
            else:
                print(c(T('ref.none'), Style.YELLOW))
                show_dump_help()
            print()
            continue
        if choice in EXIT_WORDS:
            return 'quit'
        print(c(T('act.bad'), Style.YELLOW))


def run_once(action, target: Path):
    if action == 'restore':
        restore(target)
    elif FIX_MODE == 'universal':
        apply_universal(target)
    else:
        apply_fix(target)


def drag_drop_loop():
    """跑完不退出，把 mod 文件夹拖进窗口就能接着处理下一个"""
    print()
    if FIX_MODE == 'normal' and DUMP_MESHES:
        print(T('ref.active', c(describe_active_dumps(), Style.GREEN)))
    print(c(T('ui.onlyone'), Style.RED))
    print(c(T('ui.onlyone2'), Style.RED))
    print()
    print(c(T('ui.line'), Style.GRAY))
    print(T('ui.drop'))
    print(T('ui.then'))
    if ALL_DUMPS and FIX_MODE == 'normal':
        print(T('ui.key.c', Style.GREEN, 'c', Style.RESET))
    print(T('ui.key.m', Style.GREEN, 'm', Style.RESET))
    print(T('ui.key.3', Style.GREEN, '3', Style.RESET))
    print(T('ui.key.lang', Style.GREEN, 'lang', Style.RESET))
    print(T('ui.key.q', Style.GREEN, 'q', Style.RESET))
    print(c(T('ui.line'), Style.GRAY))
    print()

    while True:
        try:
            raw = input(c(T('ui.prompt'), Style.CYAN)).strip()
        except (EOFError, KeyboardInterrupt):
            print()
            break

        if not raw:
            continue
        low = raw.lower()
        if low in EXIT_WORDS:
            print(T('ui.quit'))
            break
        # 换语言
        if low in ('lang', 'language', '语言', 'en', 'zh', 'english', 'chinese', '中文'):
            global LANG
            LANG = 'en' if low in ('en', 'english') else ('zh' if low in ('zh', 'chinese', '中文') else
                                                          ('en' if LANG == 'zh' else 'zh'))
            print(T('lang.set', LANG_NAMES[LANG]))
            print()
            continue
        # 换模式：索引与顶点修复 / 通用脸部修复
        if low in ('m', 'mode', '模式', '换模式'):
            choose_mode()
            continue
        # 看通用脸部修复的名单
        if low in ('l', 'list', '名单', '3'):
            show_universal_list()
            continue
        # 换参照组：重新选参照（通用模式不看参照）
        if low in ('c', 'juese', 'role', '角色', '换角色', '参照', '换参照'):
            if FIX_MODE == 'universal':
                print(c(T('ref.not.normal'), Style.YELLOW))
            elif ALL_DUMPS:
                choose_character()
                print(T('ref.current', describe_active_dumps()))
                print()
            else:
                print(c(T('ref.none'), Style.YELLOW))
                show_dump_help()
            continue

        # 一次拖多个文件夹时，控制台会把所有路径拼成一行（含空格的路径带引号）
        try:
            tokens = shlex.split(raw, posix=False)
        except ValueError:
            tokens = [raw]

        for token in tokens:
            path = clean_path(token)
            if not path:
                continue
            item = Path(path)
            if not item.exists():
                print(c(T('ui.notfound', path), Style.RED))
                continue

            target = item.resolve() if item.is_dir() else item.resolve().parent

            # 拖进来的是 dump 文件夹（有 json、没 ini）-> 读进来存着，不修
            if take_dump_folder(target):
                continue

            action = ask_action(target)
            if action == 'quit':
                return
            if not action:
                continue

            print(c(T('ui.line2'), Style.GRAY))
            run_once(action, target)
            print(c(T('ui.line2'), Style.GRAY))
            print()


def main():
    global FIX_MODE, LANG
    argv = sys.argv[1:]
    action = 'apply'
    lang_given = None
    for arg in argv:
        low = arg.lower()
        if low in ('apply', 'restore'):
            action = low
        elif low in MODE_KEYS:
            FIX_MODE = 'universal'
        elif low in LANG_KEYS:
            lang_given = 'en' if low in ('-en', 'en') else 'zh'
    skip = ('apply', 'restore') + MODE_KEYS + LANG_KEYS
    paths = [arg for arg in argv if arg.lower() not in skip]

    if lang_given:
        LANG = lang_given
    else:
        choose_language()       # 语言选完再打标题，免得打两遍

    print(c(T('title', TOOL_NAME), Style.CYAN))
    print(T('subtitle'))
    print()

    refresh_dumps()
    show_dump_help()

    if paths:
        set_active_dumps(None)          # 命令行调用不提问，有多少用多少
        print(T('mode.current', c(mode_text(), Style.GREEN)))
        if FIX_MODE == 'normal' and DUMP_MESHES:
            print(T('ref.active', describe_active_dumps()))
            print(T('ui.dump.after'))
        print()
    else:
        choose_mode()                   # 选模式 + 选参照（都在这一步问完），再拖 mod

    if paths:
        for raw in paths:
            item = Path(clean_path(raw))
            if not item.exists():
                print(c(T('ui.notfound', raw), Style.RED))
                continue
            target = item.resolve() if item.is_dir() else item.resolve().parent
            if take_dump_folder(target):
                continue
            run_once(action, target)
    else:
        print(T('ui.help.entry'))

    drag_drop_loop()


if __name__ == '__main__':
    try:
        main()
    except Exception as error:
        # 出错了才停住等按键；正常退出（输入 q）直接关窗口
        print('\n出错了 / Error: {}\n'.format(error))
        print(traceback.format_exc())
        try:
            input('\n按 Enter 键退出... / Press Enter to exit...')
        except EOFError:
            pass
