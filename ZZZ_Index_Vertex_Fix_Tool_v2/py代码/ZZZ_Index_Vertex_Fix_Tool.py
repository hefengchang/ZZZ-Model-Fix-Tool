ELEMENT_RE = re.compile(
    r'SemanticName:\s*(\w+)\s*\n\s*'
    r'SemanticIndex:\s*(\d+)\s*\n\s*'
    r'Format:\s*(\w+)\s*\n\s*'
    r'InputSlot:\s*(\d+)\s*\n\s*'
    r'AlignedByteOffset:\s*(\d+)')

VERTEX_LINE_RE = re.compile(
    r'^vb\d+\[(\d+)\]\+(\d+)\s+([A-Za-z_]+)(\d+)?:\s*(.*)$', re.M)


def dxgi_chunk(fmt: str, width: int = 0) -> str:
    """DXGI 格式名 -> 顶点格式记法（认不出来就按名字里的分量数猜）"""
    if fmt in DXGI_CHUNK:
        return DXGI_CHUNK[fmt]
    match = DXGI_RE.match(fmt)
    if match:
        comps = [int(x) for x in match.groups()[:4] if x]
        kind = match.group(5).upper()
        if len(comps) == 1 and width:                # 只有一个分量：按字节数还原
            return '{}B'.format(width)
        if 'FLOAT' in kind:
            return '{}{}'.format(len(comps), 'e' if comps[0] == 16 else 'f')
        if 'UINT' in kind or 'SINT' in kind:
            return '{}{}'.format(len(comps), 'H' if comps[0] == 16 else 'I')
        return '{}B'.format(sum(comps) // 8)
    if width and width % 4 == 0:
        return '{}f'.format(width // 4)
    if width and width % 2 == 0:
        return '{}e'.format(width // 2)
    return '{}B'.format(width)


def parse_vb0_text(text: str) -> dict:
    r"""-vb0=<hash>.txt -> {'stride', 'count', 'elements', 'positions', 'blends'}

    positions[i] = (x, y, z)
    blends[i]    = ((w0..w3), (i0..i3))
    """
    head, _sep, body = text.partition('vertex-data:')
    stride = count = 0
    m = re.search(r'(?m)^stride:\s*(\d+)', head)
    if m:
        stride = int(m.group(1))
    m = re.search(r'(?m)^vertex count:\s*(\d+)', head)
    if m:
        count = int(m.group(1))

    elements = []
    for em in ELEMENT_RE.finditer(head):
        elements.append({
            'semantic': em.group(1).upper(),
            'index': int(em.group(2)),
            'format': em.group(3),
            'slot': int(em.group(4)),
            'offset': int(em.group(5)),
        })

    if not count:
        count = max((int(m.group(1)) for m in VERTEX_LINE_RE.finditer(body)), default=-1) + 1

    positions = [None] * count
    weights = [None] * count
    indices = [None] * count

    for m in VERTEX_LINE_RE.finditer(body):
        i = int(m.group(1))
        if i >= count:
            continue
        semantic = m.group(3).upper()
        try:
            values = [float(x) for x in m.group(5).split(',')]
        except ValueError:
            continue
        if semantic == 'POSITION' and (m.group(4) in (None, '0')):
            positions[i] = tuple(values[:3])
        elif semantic == 'BLENDWEIGHTS':
            weights[i] = tuple(values[:4])
        elif semantic == 'BLENDINDICES':
            indices[i] = tuple(int(x) for x in values[:4])

    blends = [None] * count
    for i in range(count):
        if weights[i] is not None and indices[i] is not None:
            blends[i] = (weights[i], indices[i])

    return {'stride': stride, 'count': count, 'elements': elements,
            'positions': positions, 'blends': blends}


def load_vb0_file(path: Path) -> dict:
    """读并缓存一个 -vb0=*.txt"""
    key = str(path)
    if key not in VB0_CACHE:
        VB0_CACHE[key] = parse_vb0_text(read_text(path))
    return VB0_CACHE[key]


def texcoord_layout(elements: list):
    """从元素表里挑出 texcoord 缓冲的那几块：COLOR 在最前，然后 TEXCOORD 按序号"""
    picked = [e for e in elements if e['semantic'] == 'COLOR' and e['index'] == 0]
    picked += sorted((e for e in elements if e['semantic'] == 'TEXCOORD'),
                     key=lambda e: e['index'])
    if not picked:
        return None
    return tuple(dxgi_chunk(e['format']) for e in picked)


def find_vb0_file(folder: Path, position_hash) -> Path:
    """按 -vb0=<position_vb>.txt 找顶点数据文件，找不到就随便拿一个 -vb0=*.txt"""
    candidates = sorted(folder.glob('*-vb0=*.txt'))
    if position_hash:
        want = '-vb0={}.txt'.format(str(position_hash).lower())
        for path in candidates:
            if path.name.lower().endswith(want):
                return path
    return candidates[0] if candidates else None


def load_dump_folder(folder: Path) -> dict:
    r"""读一个 dump 根目录 -> {texcoord hash: info}

    hash.json 可以有多条（一个文件夹里多个网格）；分组名（只影响输出显示，
    也决定一次修多少）取一级子文件夹名，直接放在根目录的取文件名。
    """
    meshes = {}
    for json_path in sorted(folder.rglob('*.json')):
        try:
            data = json.loads(read_text(json_path))
        except Exception:
            continue
        entries = data if isinstance(data, list) else [data]

        for entry in entries:
            if not isinstance(entry, dict):
                continue
            tex_hash = str(entry.get('texcoord_vb') or '').lower()
            if not re.fullmatch(r'[0-9a-f]{8}', tex_hash):
                continue

            vb0_path = find_vb0_file(json_path.parent, entry.get('position_vb'))
            if vb0_path is None:
                continue
            try:
                vb0 = load_vb0_file(vb0_path)
            except Exception:
                print(c(T('dump.readerr', vb0_path), Style.YELLOW))
                continue

            layout = texcoord_layout(vb0['elements'])
            if not layout:
                continue

            relative = json_path.relative_to(folder)
            group = relative.parts[0] if len(relative.parts) > 1 else json_path.stem

            meshes[tex_hash] = {
                'mesh': entry.get('component_name') or json_path.stem,
                'character': group,
                'new_format': layout,
                'blend_hash': str(entry.get('blend_vb') or '').lower() or None,
                'position_hash': str(entry.get('position_vb') or '').lower() or None,
                'ib_hash': str(entry.get('ib') or '').lower() or None,
                'texcoord_hash': tex_hash,
                'vb0_file': vb0_path,
                'vb0_stride': vb0['stride'],
                'vertex_count': vb0['count'],
                'objects': [str(x) for x in (entry.get('object_classifications') or [])],
                'source': json_path.name,
                'from_dump': True,
            }
    return meshes


