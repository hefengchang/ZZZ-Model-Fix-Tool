def ask(prompt=''):
    """读一行输入。非交互运行（stdin 到头）时当空输入，不让它抛异常"""
    try:
        return input(prompt)
    except EOFError:
        return ''
    except KeyboardInterrupt:
        print()
        return ''


def clean_path(raw):
    raw = raw.strip()
    if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in '"\'':
        raw = raw[1:-1]
    return raw.strip()


def is_dump_folder(folder: Path) -> bool:
    """有 json、没有 ini -> 当成 dump 文件夹"""
    if not folder.is_dir():
        return False
    return any(True for _ in folder.rglob('*.json')) and not any(True for _ in folder.rglob('*.ini'))


def take_dump_folder(folder: Path) -> bool:
    """是 dump 文件夹就读进来并返回 True"""
    if not is_dump_folder(folder):
        return False
    added, total, names = load_dump_into_session(folder)
    print(c(T('ui.dump.read', total, added), Style.GREEN))
    print(T('ui.dump.after'))
    if names:
        print(T('ui.dump.newrefs', join_names(names)))
        print(T('ui.dump.usec', c('c', Style.GREEN)))
    print()
    return True


