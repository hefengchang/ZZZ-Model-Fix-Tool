def lsimg_options():
    """从设置文件读可变参数；非法值回退默认"""
    cfg = _load_config()

    def as_bool(key, default):
        v = cfg.get(key, default)
        if isinstance(v, bool):
            return v
        if isinstance(v, str):
            return v.strip().lower() not in ('0', 'false', 'no', 'off', '')
        return bool(v)

    def as_int(key, default, lo, hi):
        try:
            v = int(cfg.get(key, default))
        except (TypeError, ValueError):
            v = default
        return max(lo, min(hi, v))

    prefix = str(cfg.get('ls_prefix') or LS_PREFIX).strip() or LS_PREFIX
    mode = str(cfg.get('ls_ini_mode') or 'author').strip().lower()
    return {
        'prefix': prefix,
        'pad': as_int('ls_pad', 0, 0, 6),
        'flip': as_bool('ls_flip_vertical', True),
        'dedupe': as_bool('ls_dedupe', True),
        'pad_blur': as_bool('ls_pad_blur', True),
        'blur_dim': as_int('ls_blur_dim', LS_BLUR_DIM, 0, 255),
        'blur_vignette': as_int('ls_blur_vignette', LS_BLUR_VIGNETTE, 0, 255),
        'blur_scale_div': as_int('ls_blur_scale_div', LS_BLUR_SCALE_DIV, 1, 32),
        'ini_mode': 'builtin' if mode == 'builtin' else 'author',
    }


def lsimg_find_texconv():
    """查找随程序打包或放在程序目录中的 texconv.exe。"""
    base = _program_dir()
    bundle_dir = getattr(sys, '_MEIPASS', '')
    for c in (os.path.join(bundle_dir, 'texconv.exe') if bundle_dir else '',
              os.path.join(base, 'texconv.exe'),
              os.path.join(base, '依赖包勿删', 'texconv.exe')):
        if os.path.isfile(c):
            return c
    return ''


def lsimg_build(images_dir, mod_dir, texconv, preview=False, cache_dir='',
                progress=None, cancel=None, log=None):
    """有缓存目录就用它；没填就用临时目录，跑完删掉，不在别处留缓存。"""
    if cache_dir:
        if not preview:
            try:
                lsimg_ensure_cache_note(cache_dir)
            except OSError as e:
                raise RuntimeError('缓存目录不可用：{}'.format(e))
        if log is not None:
            log('缓存目录：{}'.format(cache_dir), 'gray')
        return _lsimg_build_impl(images_dir, mod_dir, texconv, preview,
                                 cache_dir, progress, cancel, log)
    tmp = tempfile.mkdtemp(prefix='zzz_ls_')
    if log is not None:
        log('临时目录：{}（跑完自动删除，不保留缓存）'.format(tmp), 'gray')
    try:
        return _lsimg_build_impl(images_dir, mod_dir, texconv, preview,
                                 tmp, progress, cancel, log)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def lsimg_md5(path):
    h = hashlib.md5()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def lsimg_natural_key(text):
    return [(0, int(t)) if t.isdigit() else (1, t.lower())
            for t in re.split(r'(\d+)', text)]


def _lsimg_blur_backdrop(im, Image, resample, W, H, dim_alpha,
                         vignette=LS_BLUR_VIGNETTE,
                         scale_div=LS_BLUR_SCALE_DIV):
    sw = max(32, int(round(W / float(max(1, scale_div)))))
    sh = max(10, int(round(H / float(max(1, scale_div)))))
    small = Image.new('RGBA', (sw, sh), (0, 0, 0, 255))
    scale = max(sw / float(im.width), sh / float(im.height))
    rw = max(1, int(round(im.width * scale)))
    rh = max(1, int(round(im.height * scale)))
    rs = im.resize((rw, rh), resample)
    left = (sw - rw) // 2
    top = (sh - rh) // 2
    if rw <= sw and rh <= sh:
        small.paste(rs, (left, top), rs)
    else:
        box = (max(0, -left), max(0, -top),
               min(rw, max(0, -left) + sw), min(rh, max(0, -top) + sh))
        small.paste(rs.crop(box), (max(0, left), max(0, top)))
    # 缩小再放大：整张图铺满画布，得到同一张图的模糊放大版（不拼贴）
    tile = small.resize((W, H), resample)
    dim = Image.new('RGBA', (W, H), (0, 0, 0, dim_alpha))
    tile.alpha_composite(dim)
    # 暗角：焦点椭圆 0.35×0.9，椭圆内保持透明，往外才逐渐变暗
    gw = max(8, W // 16)
    gh = max(8, H // 16)
    alpha = Image.new('L', (gw, gh))
    px = alpha.load()
    cx = (gw - 1) / 2.0
    cy = (gh - 1) / 2.0
    half_w = max(1.0, cx)
    half_h = max(1.0, cy)
    fx, fy = 0.35, 0.9
    for y in range(gh):
        for x in range(gw):
            nx = abs(x - cx) / (half_w * fx)
            ny = abs(y - cy) / (half_h * fy)
            r = (nx * nx + ny * ny) ** 0.5
            if r > 1.0:
                r = 1.0
            px[x, y] = int(vignette * r)
    alpha = alpha.resize((W, H), resample)
    black = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    black.putalpha(alpha)
    tile.alpha_composite(black)
    return tile


def lsimg_canvas_png(src_path, out_png, opts=None):
    """把源图做成 3448x1084 的透明画布 PNG，并上下翻转（游戏加载图方向）"""
    from PIL import Image
    opts = opts or lsimg_options()
    resample = getattr(getattr(Image, 'Resampling', Image), 'LANCZOS')
    im = Image.open(src_path)
    try:
        im.seek(0)
    except Exception:
        pass
    im = im.convert('RGBA')
    W, H = LS_CANVAS_W, LS_CANVAS_H
    canvas = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    vw = min(int(round(H * LS_VISIBLE_ASPECT)), W)
    win_x = (W - vw) // 2
    scale = H / float(im.height)
    draw_w = int(round(im.width * scale))
    if draw_w >= vw:
        cw = min(max(1, int(round(vw / scale))), im.width)
        sx = (im.width - cw) // 2
        part = im.crop((sx, 0, sx + cw, im.height)).resize((vw, H), resample)
        canvas.alpha_composite(part, (win_x, 0))
    else:
        if opts.get('pad_blur', True):
            back = _lsimg_blur_backdrop(
                im, Image, resample, W, H, opts['blur_dim'],
                opts['blur_vignette'], opts['blur_scale_div'])
            canvas.alpha_composite(back.crop((win_x, 0, win_x + vw, H)), (win_x, 0))
        part = im.resize((max(1, draw_w), H), resample)
        canvas.alpha_composite(part, (win_x + (vw - draw_w) // 2, 0))
    if opts.get('flip', True):
        canvas = canvas.transpose(Image.FLIP_TOP_BOTTOM)
    os.makedirs(os.path.dirname(out_png), exist_ok=True)
    canvas.save(out_png, 'PNG')


def lsimg_texconv(png_path, out_dir, texconv):
    """调 texconv 转 BC7 SRGB、带 DX10 头"""
    try:
        enc = locale.getpreferredencoding(False) or 'utf-8'
    except Exception:
        enc = 'utf-8'
    flags = 0x08000000 if os.name == 'nt' else 0
    cmd = [texconv, '-nologo', '-f', 'BC7_UNORM_SRGB', '-srgbi', '-dx10',
           '-y', '-m', '1', '-o', out_dir, png_path]
    res = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                         text=True, encoding=enc, errors='replace',
                         creationflags=flags)
    if res.returncode != 0:
        tail = (res.stdout or '').strip().splitlines()
        raise RuntimeError('texconv 返回码 {}：{}'.format(
            res.returncode, tail[-1] if tail else ''))
    out = os.path.join(out_dir, os.path.splitext(os.path.basename(png_path))[0] + '.dds')
    if not os.path.isfile(out):
        raise RuntimeError('texconv 没有输出 dds')
    return out


def _lsimg_try_author_ini(mod_dir):
    """跑 mod 自带的 loading_screen_manager.py::generate_ini_file"""
    py_file = os.path.join(mod_dir, 'loading_screen_manager.py')
    if not os.path.isfile(py_file):
        return False, 'mod 里没有 loading_screen_manager.py'
    try:
        with open(py_file, 'r', encoding='utf-8', errors='replace') as f:
            src = f.read()
        tree = ast.parse(src)
        node = next((n for n in tree.body
                     if isinstance(n, ast.FunctionDef)
                     and n.name == 'generate_ini_file'), None)
        if node is None:
            return False, '没找到 generate_ini_file'
        code = ast.get_source_segment(src, node)
        if not code:
            return False, '提取函数失败'
        ns = {'os': os, 'sys': sys, '__name__': 'author_mod'}
        exec(compile(code, '<author>', 'exec'), ns)
        old = os.getcwd()
        try:
            os.chdir(mod_dir)
            ok, msg = ns['generate_ini_file'](mod_dir)
        finally:
            os.chdir(old)
        return bool(ok), str(msg)
    except Exception as e:
        return False, '{}: {}'.format(type(e).__name__, e)


def _lsimg_builtin_ini(mod_dir):
    """按 custom_loading_screen.ini 的接口生成 autogenerated.ini"""
    ini_body = os.path.join(mod_dir, 'custom_loading_screen.ini')
    text = open(ini_body, 'r', encoding='utf-8', errors='replace').read()
    declared = [m.group(1) for m in
                re.finditer(r'(?im)^\s*global\s+\$(\w+)', text)]
    declared_low = {d.lower() for d in declared}
    used = sorted({m.group(1) for m in re.finditer(r'\$(\w+)', text)})
    external = [u for u in used if u.lower() not in declared_low]
    sections = [m.group(1) for m in
                re.finditer(r'(?im)^\[([^\]]+)\]', text)]
    runs = sorted({m.group(1) for m in
                   re.finditer(r'(?im)^\s*run\s*=\s*(\w+)', text)})
    missing = [r for r in runs if r not in sections]
    ns_m = re.search(r'(?im)^\s*namespace\s*=\s*(\S+)', text)
    namespace = ns_m.group(1) if ns_m else 'custom-loading-screen'

    total_var = next((e for e in external
                      if re.search(r'total|count|number|num', e, re.I)),
                     external[0] if external else 'total_dds_number')
    t_name = total_var
    pat = re.compile(r'(?im)^\s*\$(\w+)\s*=[^\r\n]*\$' + re.escape(t_name) + r'\b')
    idx_cand = sorted({'$' + m.group(1) for m in pat.finditer(text)})
    index_var = next((c for c in idx_cand
                      if re.search(r'random|index|idx', c, re.I)), None)
    if not index_var:
        index_var = idx_cand[0] if idx_cand else '$random_number'
    cmd_list = next((m for m in missing
                     if re.search(r'Override|Texture|Apply|Select', m, re.I)), None)
    if not cmd_list:
        cmd_list = missing[0] if missing else 'CommandListOverrideTexture'

    mod_dds = os.path.join(mod_dir, 'dds')
    all_dds = []
    if os.path.isdir(mod_dds):
        for root, _dirs, files in os.walk(mod_dds):
            for fn in files:
                if fn.lower().endswith('.dds'):
                    rel = os.path.relpath(os.path.join(root, fn), mod_dir)
                    all_dds.append(rel.replace('\\', '/'))
    all_dds.sort(key=lsimg_natural_key)

    lines = ['namespace = {}'.format(namespace),
             '; Generated by 加载屏幕图片添加器', '',
             '[Constants]',
             'global ${} = {}'.format(total_var, len(all_dds)), '',
             '[{}]'.format(cmd_list)]
    for k in range(len(all_dds)):
        lines.append('{} {} == {}'.format('if' if k == 0 else 'else if',
                                          index_var, k + 1))
        lines.append('  ps-t0 = Resource_{}'.format(k + 1))
    if all_dds:
        lines.append('endif')
        lines.append('')
        for k, rel in enumerate(all_dds):
            lines.append('[Resource_{}]'.format(k + 1))
            lines.append('filename = {}'.format(rel))
            lines.append('')
    out = os.path.join(mod_dir, 'autogenerated.ini')
    with open(out, 'w', encoding='utf-8', newline='') as f:
        f.write('\r\n'.join(lines) + '\r\n')
    return True, '内置生成器'


def _lsimg_build_impl(images_dir, mod_dir, texconv, preview, cache_dir,
                      progress=None, cancel=None, log=None):
    """加载屏幕图片添加器主流程。取消返回 None。"""
    def note(text, tag=None):
        if log is not None:
            log(text, tag)

    try:
        from PIL import Image  # noqa: F401
    except Exception as e:
        raise RuntimeError('缺少 Pillow，请先安装：pip install pillow（{}）'.format(e))
    if cancel is not None and cancel.is_set():
        return None
    opts = lsimg_options()
    note('参数：前缀 {} · 补零 {} · 翻转 {} · 去重 {} · 模糊 1/{}'.format(
        opts['prefix'], opts['pad'], '开' if opts['flip'] else '关',
        '开' if opts['dedupe'] else '关', opts['blur_scale_div']), 'gray')

    cache_dds = os.path.join(cache_dir, 'dds')
    tmp_dir = os.path.join(cache_dir, 'temp')
    index_path = os.path.join(cache_dir, 'dds-index.json')
    map_path = os.path.join(cache_dir, 'cache-map.json')
    if not preview:
        os.makedirs(cache_dds, exist_ok=True)
        os.makedirs(tmp_dir, exist_ok=True)

    index = {}
    try:
        with open(index_path, encoding='utf-8') as f:
            index = json.load(f)
    except Exception:
        index = {}
    if not isinstance(index, dict):
        index = {}
    cache_map = {}
    try:
        with open(map_path, encoding='utf-8') as f:
            cache_map = json.load(f)
    except Exception:
        cache_map = {}
    if not isinstance(cache_map, dict):
        cache_map = {}

    # ---- mod 里已有 dds 的 MD5 索引 ----
    mod_dds = os.path.join(mod_dir, 'dds')
    by_md5 = {}
    new_index = {}
    dds_count = 0
    if os.path.isdir(mod_dds):
        for root, _dirs, files in os.walk(mod_dds):
            for fn in files:
                if not fn.lower().endswith('.dds'):
                    continue
                fp = os.path.join(root, fn)
                st = os.stat(fp)
                rel = os.path.relpath(fp, mod_dir).replace('\\', '/')
                ent = index.get(rel)
                if (isinstance(ent, dict) and ent.get('size') == st.st_size
                        and ent.get('mtime') == st.st_mtime_ns
                        and ent.get('md5')):
                    md5 = ent.get('md5')
                else:
                    md5 = lsimg_md5(fp)
                new_index[rel] = {'size': st.st_size,
                                  'mtime': st.st_mtime_ns, 'md5': md5}
                by_md5.setdefault(md5, rel)
                dds_count += 1
    note('mod 里已有 dds：{} 个'.format(dds_count))

    def _sort_key(p):
        try:
            return (os.stat(p).st_mtime_ns, os.path.basename(p).lower())
        except OSError:
            return (0, os.path.basename(p).lower())

    # ---- 收集图片 ----
    try:
        names = os.listdir(images_dir)
    except OSError as e:
        raise RuntimeError('读不了图片文件夹：{}'.format(e))
    images = [os.path.join(images_dir, n) for n in names
              if os.path.splitext(n)[1].lower() in LS_IMG_EXTS
              and os.path.isfile(os.path.join(images_dir, n))]
    images.sort(key=_sort_key)

    # ---- 内容去重（顺便记下每张图的 MD5，缓存要用它比对） ----
    seen = {}
    hash_by_path = {}
    uniq = []
    dups = []
    for p in images:
        if cancel is not None and cancel.is_set():
            return None
        h = lsimg_md5(p)
        hash_by_path[p] = h
        if not opts['dedupe']:
            continue
        if h in seen:
            dups.append((p, seen[h]))
        else:
            seen[h] = p
            uniq.append(p)
    if opts['dedupe']:
        images = uniq
    if dups:
        note('发现内容重复的图 {} 个，会移到 图片\\_重复'.format(len(dups)), 'warn')
        if not preview:
            dup_dir = os.path.join(images_dir, '_重复')
            os.makedirs(dup_dir, exist_ok=True)
            for p, same in dups:
                dest = os.path.join(dup_dir, os.path.basename(p))
                if os.path.exists(dest):
                    stem, ext = os.path.splitext(os.path.basename(p))
                    dest = os.path.join(dup_dir, '{}_{}{}'.format(
                        stem, time.strftime('%H%M%S'), ext))
                try:
                    shutil.move(p, dest)
                except OSError as e:
                    note('移动重复图失败：{}（{}）'.format(p, e), 'err')

    # ---- 编号：已有 cgN 保留，其余按时间接续 ----
    pat = re.compile('^' + re.escape(opts['prefix']) + r'(\d+)$')
    numbered = []
    others = []
    for p in images:
        stem = os.path.splitext(os.path.basename(p))[0]
        (numbered if pat.match(stem) else others).append(p)
    numbered.sort(key=_sort_key)
    others.sort(key=_sort_key)
    keep = {}
    for p in numbered:
        m = pat.match(os.path.splitext(os.path.basename(p))[0])
        if m:
            keep.setdefault(int(m.group(1)), p)
    max_no = max(keep) if keep else 0
    plan = []
    next_no = max_no + 1
    for p in others:
        ext = os.path.splitext(p)[1].lower()
        num_str = (str(next_no).zfill(opts['pad'])
                   if opts['pad'] > 0 else str(next_no))
        new_name = '{}{}{}'.format(opts['prefix'], num_str, ext)
        next_no += 1
        if os.path.basename(p) == new_name:
            continue
        plan.append((p, new_name))
    renamed = 0
    if plan:
        if preview:
            note('预览：待改名 {} 张（{} … {}）'.format(
                len(plan), plan[0][1], plan[-1][1]), 'gray')
        else:
            stage = []
            for i, (p, new_name) in enumerate(plan):
                tmp_name = '__rn_{}_{}_{}'.format(
                    time.strftime('%H%M%S'), i, os.path.splitext(p)[1])
                tmp_path = os.path.join(os.path.dirname(p), tmp_name)
                try:
                    os.replace(p, tmp_path)
                    stage.append((tmp_path, os.path.join(
                        os.path.dirname(p), new_name)))
                except OSError as e:
                    note('改名失败：{}（{}）'.format(p, e), 'err')
            for tmp_path, final in stage:
                try:
                    os.replace(tmp_path, final)
                    renamed += 1
                except OSError as e:
                    note('改名失败：{}（{}）'.format(tmp_path, e), 'err')
            note('已按时间改名 {} 张'.format(renamed), 'gray')

    jobs = []
    try:
        for n in os.listdir(images_dir):
            stem, ext = os.path.splitext(n)
            if ext.lower() in LS_IMG_EXTS and pat.match(stem):
                fp = os.path.join(images_dir, n)
                if os.path.isfile(fp):
                    jobs.append((int(stem[len(opts['prefix']):]), fp))
    except OSError:
        pass
    jobs.sort()
    total = len(jobs)
    note('当前共 {} 张图'.format(total))

    # ---- 转换 + 判重 ----
    converted = reused = failed = 0
    to_add = []
    already = []
    fail_list = []
    for i, (idx, path) in enumerate(jobs):
        if cancel is not None and cancel.is_set():
            return None
        base = os.path.splitext(os.path.basename(path))[0]
        cache_file = os.path.join(cache_dds, base + '.dds')
        st = os.stat(path)
        src_md5 = hash_by_path.get(path) or lsimg_md5(path)
        need = True
        if os.path.isfile(cache_file) and os.path.getsize(cache_file) > 1024:
            rec = cache_map.get(base)
            # 缓存必须对应同一张源图（按内容 MD5 比），不是同一张就重转
            if isinstance(rec, dict) and rec.get('md5') == src_md5:
                need = False
        if need:
            if preview:
                converted += 1
                if progress is not None:
                    progress(i + 1, total, base)
                continue
            png = os.path.join(tmp_dir, base + '.png')
            try:
                lsimg_canvas_png(path, png, opts)
                lsimg_texconv(png, cache_dds, texconv)
                cache_map[base] = {'size': st.st_size,
                                   'mtime': st.st_mtime_ns, 'md5': src_md5}
                converted += 1
                note('[{}/{}] {} -> {}.dds'.format(i + 1, total, base, base), 'gray')
            except Exception as e:
                failed += 1
                fail_list.append('{}：{}'.format(base, e))
                note('[{}/{}] {} 失败：{}'.format(i + 1, total, base, e), 'err')
                try:
                    if os.path.exists(png):
                        os.remove(png)
                except OSError:
                    pass
                if progress is not None:
                    progress(i + 1, total, base)
                continue
            try:
                if os.path.exists(png):
                    os.remove(png)
            except OSError:
                pass
        else:
            reused += 1
        if preview:
            if progress is not None:
                progress(i + 1, total, base)
            continue
        md5 = lsimg_md5(cache_file)
        dds_name = base + '.dds'
        if md5 in by_md5:
            already.append((dds_name, by_md5[md5]))
        else:
            to_add.append((cache_file, dds_name))
            by_md5[md5] = dds_name
        if progress is not None:
            progress(i + 1, total, base)

    if preview:
        note('预览：需要转换 {} 张，其余复用缓存；不写任何文件'.format(converted), 'accent')
        return {'images': total, 'converted': converted, 'reused': reused,
                'failed': failed, 'added': 0, 'already': 0,
                'renamed': renamed, 'duplicates': len(dups),
                'ini_ok': False, 'ini_how': '', 'preview': True}

    # ---- 部署到 dds\<日期>\ ----
    added = 0
    date_dir = None
    if to_add:
        os.makedirs(mod_dds, exist_ok=True)
        stamp = time.strftime('%Y-%m-%d')
        cand = os.path.join(mod_dds, stamp)
        k = 2
        while os.path.exists(cand):
            cand = os.path.join(mod_dds, '{}_{}'.format(stamp, k))
            k += 1
        date_dir = cand
        os.makedirs(date_dir, exist_ok=True)
        for src, name in to_add:
            try:
                shutil.copy2(src, os.path.join(date_dir, name))
                added += 1
            except OSError as e:
                failed += 1
                fail_list.append('{}：{}'.format(name, e))
                note('复制失败：{}（{}）'.format(name, e), 'err')
        note('新增 {} 张 → {}'.format(added, date_dir), 'ok')

    # ---- 刷新 autogenerated.ini ----
    ini_ok = False
    ini_how = ''
    ini_path = os.path.join(mod_dir, 'autogenerated.ini')
    if total > 0:
        if os.path.isfile(ini_path):
            try:
                shutil.copy2(ini_path, ini_path + '.bak')
            except OSError as e:
                note('备份 autogenerated.ini 失败：{}'.format(e), 'warn')
        if opts['ini_mode'] == 'builtin':
            ini_ok, ini_how = False, ''
            note('按设置使用内置生成器', 'gray')
        else:
            ini_ok, ini_how = _lsimg_try_author_ini(mod_dir)
            if not ini_ok:
                note('自带生成程序没成功（{}），改用内置生成器'.format(ini_how), 'warn')
        if not ini_ok:
            try:
                ini_ok, ini_how = _lsimg_builtin_ini(mod_dir)
            except Exception as e:
                ini_ok = False
                ini_how = '内置生成器失败：{}'.format(e)
                note(ini_how, 'err')
    else:
        note('图片文件夹是空的，这次不动 autogenerated.ini', 'warn')

    # ---- 保存索引 ----
    try:
        if added:
            for root, _dirs, files in os.walk(mod_dds):
                for fn in files:
                    if not fn.lower().endswith('.dds'):
                        continue
                    fp = os.path.join(root, fn)
                    rel = os.path.relpath(fp, mod_dir).replace('\\', '/')
                    if rel in new_index:
                        continue
                    st = os.stat(fp)
                    new_index[rel] = {'size': st.st_size,
                                      'mtime': st.st_mtime_ns,
                                      'md5': lsimg_md5(fp)}
        os.makedirs(cache_dir, exist_ok=True)
        with open(index_path, 'w', encoding='utf-8') as f:
            json.dump(new_index, f, ensure_ascii=False)
        with open(map_path, 'w', encoding='utf-8') as f:
            json.dump(cache_map, f, ensure_ascii=False)
    except OSError as e:
        note('保存缓存索引失败：{}'.format(e), 'warn')
    if fail_list:
        note('失败清单：{}'.format(' / '.join(fail_list)), 'warn')

    return {'images': total, 'converted': converted, 'reused': reused,
            'failed': failed, 'added': added, 'already': len(already),
            'renamed': renamed, 'duplicates': len(dups),
            'ini_ok': ini_ok, 'ini_how': ini_how, 'preview': False}


