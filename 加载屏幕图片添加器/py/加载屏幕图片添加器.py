    # ---------- 构建 ----------
    def start(self):
        if self.running:
            self.cancel_event.set()
            self._set_chip('正在停止…', 'warn')
            self.btn_start.config(state='disabled')
            return
        images = self.images_entry.get().strip().strip('"')
        mod_dir = self.mod_entry.get().strip().strip('"')
        if not os.path.isdir(images):
            messagebox.showinfo('提示', '图片文件夹不存在：\n\n{}'.format(images),
                                parent=self.root)
            return
        found_mod = self._find_mod(mod_dir) if mod_dir else None
        if not found_mod:
            messagebox.showinfo(
                '提示',
                'mod 文件夹不对：里面（或往下三层）要有 custom_loading_screen.ini。\n\n'
                '本工具不提供 mod 本体，需要先装好 custom_loading_screen。',
                parent=self.root)
            return
        if found_mod != mod_dir:
            self._log('已在下面找到加载屏幕 mod：{}'.format(found_mod), 'gray')
            mod_dir = found_mod
            self.mod_entry.delete(0, 'end')
            self.mod_entry.insert(0, mod_dir)
        texconv = lsimg_find_texconv()
        if not texconv:
            messagebox.showerror(
                '内置转换器缺失',
                '程序里没有找到内置的 texconv.exe。\n\n'
                '正常发布包会把它放在程序目录或「依赖包勿删\\」里；'
                '这里缺了说明当前程序不完整，请重新下载完整包。',
                parent=self.root)
            return
        preview = bool(self.preview.get())
        if not preview:
            ok = messagebox.askyesno(
                '确认构建',
                '把图片装进这个 mod？\n\n图片：{}\nmod：{}\n\n'
                '不会删已有 dds；会先备份 autogenerated.ini。确定开始吗？'.format(
                    images, mod_dir), parent=self.root)
            if not ok:
                return
        self._save_paths()
        self.running = True
        self.cancel_event = threading.Event()
        self.btn_start.config(text='■ 停止', bg=DANGER, fg='white',
                              activebackground='#a52f23', activeforeground='white')
        self.progress.configure(mode='determinate', maximum=100, value=0)
        self.prog_label.config(text='0/0')
        self._set_chip('预览中' if preview else '构建中', 'accent')
        self._set_status('正在收集图片…', 'busy')
        cache_dir = self.cache_entry.get().strip().strip('"')
        if cache_dir and not preview:
            try:
                lsimg_ensure_cache_note(cache_dir)
            except OSError as e:
                self._log('缓存目录不可用（会用临时目录）：{}'.format(e), 'warn')
                cache_dir = ''
        self._log('=' * 62, 'gray')
        self._log('开始加载屏幕构建（{}）：{}'.format(
            '预览' if preview else '写入', mod_dir), 'accent')
        self._log('=' * 62, 'gray')
        threading.Thread(target=self._worker,
                         args=(images, mod_dir, texconv, preview, cache_dir),
                         daemon=True).start()

    def _worker(self, images, mod_dir, texconv, preview, cache_dir):
        try:
            def progress(done, total, name):
                self.q.put(('prog', done, total, name))

            def log(text, tag=None):
                self.q.put(('msg', text, tag))

            stats = lsimg_build(images, mod_dir, texconv, preview=preview,
                                cache_dir=cache_dir, progress=progress,
                                cancel=self.cancel_event, log=log)
            if stats is None:
                self.q.put(('aborted', preview))
            else:
                self.q.put(('done', stats))
        except Exception as e:
            self.q.put(('error', '{}: {}'.format(type(e).__name__, e)))

    def _finish(self, stats, aborted=False):
        self.running = False
        self.btn_start.config(text='▶ 开始构建', bg=ACCENT, fg=ACCENT_INK,
                              activebackground='#ffcf00',
                              activeforeground=ACCENT_INK, state='normal')
        try:
            self.progress.stop()
            self.progress.configure(mode='determinate', maximum=100, value=0)
        except Exception:
            pass
        self.prog_label.config(text='')
        if aborted or self.cancel_event.is_set():
            self._set_chip('已停止', 'warn')
            self._set_status('已停止构建（已处理的文件保持现状）。', 'warn')
            self._log('已停止加载屏幕构建（已处理的文件保持现状）。', 'warn')
            return
        preview = bool(stats.get('preview'))
        summary = '图 {} 张 · 转换 {} · 复用缓存 {} · 失败 {} · 新增 {} · 已存在 {}'.format(
            stats['images'], stats['converted'], stats['reused'],
            stats['failed'], stats['added'], stats['already'])
        if preview:
            self._set_chip('预览完成', 'warn')
            self._set_status(summary + '（预览，未写入）', 'warn')
            self._log('加载屏幕预览完成（未写入）：{}'.format(summary), 'warn')
        elif stats['failed']:
            self._set_chip('部分失败', 'err')
            self._set_status(summary, 'err')
            self._log('加载屏幕构建完成（有失败）：{}'.format(summary), 'warn')
        else:
            self._set_chip('构建完成 ✔', 'ok')
            self._set_status(summary + ' · 进游戏按 F10 重载模组。', 'ok')
            self._log('加载屏幕构建完成：{}'.format(summary), 'ok')
        if stats.get('ini_ok'):
            self._log('autogenerated.ini 已更新（{}）'.format(
                stats.get('ini_how') or '内置生成器'), 'ok')
        elif not preview:
            self._log('autogenerated.ini 未更新（详见日志）', 'warn')
        self._log('-' * 62, 'gray')

    def _error(self, msg):
        self.running = False
        self.btn_start.config(text='▶ 开始构建', bg=ACCENT, fg=ACCENT_INK,
                              activebackground='#ffcf00',
                              activeforeground=ACCENT_INK, state='normal')
        try:
            self.progress.stop()
            self.progress.configure(mode='determinate', maximum=100, value=0)
        except Exception:
            pass
        self._set_chip('构建失败', 'err')
        self._set_status('加载屏幕构建失败：{}'.format(msg), 'err')
        self._log('加载屏幕构建失败：{}'.format(msg), 'err')
        messagebox.showerror('加载屏幕构建失败', msg, parent=self.root)

    # ---------- 队列 ----------
    def _poll(self):
        try:
            while True:
                ev = self.q.get_nowait()
                if ev[0] == 'msg':
                    self._log(ev[1], ev[2])
                elif ev[0] == 'prog':
                    _, done, total, name = ev
                    self.progress.configure(maximum=max(total or 1, 1), value=done)
                    self.prog_label.config(text='{}/{}'.format(done, total or 1))
                    if name:
                        self._set_status('处理 {}'.format(name), 'busy')
                elif ev[0] == 'done':
                    self._finish(ev[1])
                elif ev[0] == 'aborted':
                    self._finish(None, aborted=True)
                elif ev[0] == 'error':
                    self._error(ev[1])
        except queue.Empty:
            pass
        self.root.after(80, self._poll)

    # ---------- 关闭 ----------
    def _on_close(self):
        if self.running:
            if not messagebox.askyesno(
                    '正在构建', '构建还没结束，确定要退出吗？\n\n'
                                '已处理的文件保持现状。', parent=self.root):
                return
            self.cancel_event.set()
        try:
            cfg = self._collect_cfg()
            cfg['window_geometry'] = self.root.geometry()
            _save_config(cfg)
        except Exception:
            pass
        self.root.destroy()


