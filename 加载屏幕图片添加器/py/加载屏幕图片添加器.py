    @staticmethod
    def _find_mod(path):
        """给了上一级目录也能往下三层找到含 custom_loading_screen.ini 的那层"""
        if not path or not os.path.isdir(path):
            return None
        if os.path.isfile(os.path.join(path, 'custom_loading_screen.ini')):
            return path
        base = os.path.abspath(path).rstrip(os.sep)
        base_depth = base.count(os.sep)
        hits = []
        for root, dirs, files in os.walk(base):
            depth = root.rstrip(os.sep).count(os.sep) - base_depth
            if depth > 3:
                dirs[:] = []
                continue
            if 'custom_loading_screen.ini' in files:
                hits.append(root)
        return min(hits, key=len) if hits else None

    # ---------- 拖入 ----------
    def _on_drop(self, event):
        if self.running:
            self._log('正在构建，已忽略拖入的文件夹。', 'warn')
            return
        try:
            paths = list(self.root.tk.splitlist(getattr(event, 'data', '')))
        except Exception:
            paths = []
        if not paths:
            return
        p = paths[0]
        if os.path.isdir(p) and os.path.isfile(
                os.path.join(p, 'custom_loading_screen.ini')):
            self._set_mod_dir(p)
        elif (os.path.isfile(p)
              and os.path.basename(p) == 'custom_loading_screen.ini'):
            self._set_mod_dir(os.path.dirname(p))
        elif os.path.isdir(p):
            self.images_entry.delete(0, 'end')
            self.images_entry.insert(0, os.path.abspath(p))
            self._save_paths()
            self._log('图片目录：{}'.format(os.path.abspath(p)), 'accent')
        else:
            self._log('请拖入图片文件夹或含 custom_loading_screen.ini 的 mod 文件夹。',
                      'warn')

    # ---------- 缓存清理 ----------
    def clear_cache_files(self):
        """只删缓存目录里的 dds/temp/索引，保留说明.txt；不动其他文件"""
        if self.running:
            messagebox.showinfo('提示', '正在构建，等这次跑完再清缓存。', parent=self.root)
            return
        cache_dir = (self.cache_entry.get().strip().strip('"')
                     or lsimg_default_cache_dir())
        if not cache_dir:
            messagebox.showinfo('提示', '缓存目录是空的，没有缓存可清。', parent=self.root)
            return
        if not os.path.isdir(cache_dir):
            messagebox.showinfo('提示', '缓存目录不存在：\n\n{}'.format(cache_dir),
                                parent=self.root)
            return
        try:
            same = (os.path.normcase(os.path.realpath(cache_dir))
                    == os.path.normcase(os.path.realpath(_program_dir())))
        except Exception:
            same = False
        if same:
            messagebox.showerror('不能清空', '缓存目录不能是程序目录。', parent=self.root)
            return
        if not messagebox.askyesno(
                '清空缓存',
                '删除这个目录里的缓存？\n\n{}\n\n'
                '会删：dds\\、temp\\、dds-index.json、cache-map.json\n'
                '保留：说明.txt 和其他文件'.format(cache_dir),
                parent=self.root):
            return
        removed = failed = 0
        for name in ('dds', 'temp'):
            p = os.path.join(cache_dir, name)
            if os.path.isdir(p):
                try:
                    shutil.rmtree(p)
                    removed += 1
                except OSError as e:
                    failed += 1
                    self._log('删除缓存失败：{}（{}）'.format(p, e), 'err')
        for name in ('dds-index.json', 'cache-map.json'):
            p = os.path.join(cache_dir, name)
            if os.path.isfile(p):
                try:
                    os.remove(p)
                    removed += 1
                except OSError as e:
                    failed += 1
                    self._log('删除缓存失败：{}（{}）'.format(p, e), 'err')
        if failed:
            self._set_status('缓存清空完成，但有 {} 项失败（详见日志）'.format(failed),
                             'err')
            self._log('缓存清空完成（有失败）：成功 {} · 失败 {}'.format(
                removed, failed), 'warn')
        else:
            self._set_status('缓存已清空：{} 项'.format(removed), 'ok')
            self._log('缓存已清空：{}（删了 {} 项，说明.txt 保留）'.format(
                cache_dir, removed), 'ok')

