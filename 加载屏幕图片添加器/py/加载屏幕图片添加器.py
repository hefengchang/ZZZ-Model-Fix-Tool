class App:
    def __init__(self, root):
        self.root = root
        self.q = queue.Queue()
        self.running = False
        self.cancel_event = threading.Event()
        cfg = _seed_config()
        root.title('{} {}'.format(APP_NAME, APP_VERSION))
        geom = cfg.get('window_geometry')
